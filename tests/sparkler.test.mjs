import test from "node:test";
import assert from "node:assert/strict";
import {
  SparklerModel,
  BURN_SECONDS,
  SPARKLER_COLORS,
} from "../src/fireworks/sparkler/model.js";
import { SparklerSound } from "../src/fireworks/sparkler/sound.js";
const advance = (m, seconds) => {
  for (let i = 0; i < Math.ceil(seconds * 60); i++) m.step(1 / 60);
};
test("Fuljhadi begins unlit, moves without sparks, burns for 38 seconds and preserves the grip as coating shortens", () => {
  const m = new SparklerModel();
  m.resize(0.78);
  m.input(0.7, 0.4);
  m.step(0.016);
  assert.equal(m.burning, false);
  assert.equal(m.particles.length, 0);
  assert.equal(m.trails.length, 0);
  assert.equal(m.tip.x, m.world(0.7, 0.4).x);
  m.restart();
  const grip = m.tip.y - m.coatTip;
  assert.ok(m.ignite());
  assert.equal(m.ignite(), false);
  advance(m, 10);
  assert.ok(m.burning);
  assert.ok(m.coatTip < 3.35);
  assert.ok(Math.abs(m.tip.y - m.coatTip - grip) < 1e-8);
  assert.ok(m.particles.length > 0);
  advance(m, 27.5);
  assert.ok(m.burning);
  advance(m, 0.6);
  assert.equal(m.burning, false);
  assert.equal(m.progress, 1);
  assert.equal(m.remaining, 0);
  assert.ok(Math.abs(m.coatTip - 1.9) < 1e-9);
  advance(m, 3);
  assert.equal(m.particles.length, 0);
  assert.equal(m.smoke.length, 0);
  assert.ok(m.ignite());
  assert.equal(m.elapsed, 0);
  assert.equal(m.coatTip, 3.35);
});
test("each selected color affects newly emitted sparks immediately; rainbow emits all six colors", () => {
  const m = new SparklerModel();
  m.ignite();
  for (const color of SPARKLER_COLORS.filter((c) => c.id !== "rainbow")) {
    m.setColor(color.id);
    m.clear();
    advance(m, 0.2);
    assert.ok(m.particles.length);
    assert.ok(m.particles.every((p) => p.color === color.hex));
  }
  m.setMode("rainbow");
  m.clear();
  advance(m, 1);
  assert.equal(new Set(m.particles.map((p) => p.color)).size, 6);
  m.setMode("classic");
  assert.equal(m.color, "yellow");
  m.setMode("painting");
  assert.equal(m.mode, "painting");
});
test("circle, spiral and figure-eight trails are generated by actual input and pass through its sampled coordinates", () => {
  for (const shape of ["circle", "spiral", "infinity"]) {
    const m = new SparklerModel();
    m.resize(1);
    m.setMode("painting");
    m.ignite();
    let last;
    for (let i = 0; i <= 120; i++) {
      const t = (i / 120) * Math.PI * 2,
        r = shape === "spiral" ? 0.07 + (i / 120) * 0.18 : 0.2;
      const x = 0.5 + Math.cos(t) * r,
        y = 0.45 + (shape === "infinity" ? Math.sin(t * 2) : Math.sin(t)) * r;
      m.input(x, y);
      m.step(1 / 60);
      const target = m.world(x, y);
      const end = m.trails.at(-1);
      assert.ok(Math.abs(end.bx - target.x) < 1e-8);
      assert.ok(Math.abs(end.by - target.y) < 1e-8);
      last = { x, y };
    }
    assert.ok(m.trails.length > 150);
    assert.ok(Math.abs(m.normalized.x - last.x) < 1e-8);
    const first = m.trails[0];
    m.burning = false;
    advance(m, 13);
    assert.ok(!m.trails.includes(first));
    assert.equal(m.trails.length, 0);
  }
});
test("fast movement creates wider trails; clearing preserves burn; restart resets it; reduced mode stays bounded", () => {
  const slow = new SparklerModel(),
    fast = new SparklerModel();
  slow.ignite();
  fast.ignite();
  slow.input(0.51, 0.42);
  fast.input(0.9, 0.42);
  slow.step(0.02);
  fast.step(0.02);
  assert.ok(fast.trails[0].width > slow.trails[0].width);
  fast.clear();
  assert.equal(fast.trails.length, 0);
  assert.ok(fast.burning);
  fast.restart();
  assert.equal(fast.burning, false);
  assert.equal(fast.hasLit, false);
  assert.equal(fast.remaining, BURN_SECONDS);
  const m = new SparklerModel();
  m.low = true;
  m.reduced = true;
  m.ignite();
  for (let i = 0; i < 1200; i++) {
    m.input((i % 100) / 100, (i % 70) / 100);
    m.step(0.016);
    assert.ok(m.particles.length <= 300);
    assert.ok(m.trails.length <= 2200);
    assert.ok(m.smoke.length <= 40);
  }
  assert.equal(m.rotation, 0);
});
test("sparkler sound uses a looping recording, fades with burnout, pans, mutes and releases all sources", async () => {
  const oldWindow = globalThis.window,
    oldFetch = globalThis.fetch;
  let made = 0;
  const sources = [];
  const param = () => ({
    value: 0,
    setValueAtTime(v) {
      this.value = v;
    },
    linearRampToValueAtTime(v) {
      this.value = v;
    },
    setTargetAtTime(v) {
      this.value = v;
    },
  });
  const node = () => ({ connect() {}, disconnect() {} });
  const buffer = (n, l, s) => {
    const channels = Array.from({ length: n }, () =>
      new Float32Array(l).fill(0.1),
    );
    return {
      sampleRate: s,
      numberOfChannels: n,
      length: l,
      duration: l / s,
      getChannelData: (c) => channels[c],
    };
  };
  class Audio {
    constructor() {
      made++;
      this.sampleRate = 8000;
      this.currentTime = 0;
      this.state = "suspended";
      this.destination = node();
    }
    async resume() {
      this.state = "running";
    }
    async suspend() {
      this.state = "suspended";
    }
    async close() {
      this.state = "closed";
    }
    createGain() {
      return { ...node(), gain: param() };
    }
    createDynamicsCompressor() {
      return {
        ...node(),
        threshold: param(),
        knee: param(),
        ratio: param(),
        attack: param(),
        release: param(),
      };
    }
    createWaveShaper() {
      return node();
    }
    createStereoPanner() {
      return { ...node(), pan: param() };
    }
    createBuffer(...a) {
      return buffer(...a);
    }
    async decodeAudioData() {
      return buffer(1, 36000, 8000);
    }
    createBufferSource() {
      const source = {
        ...node(),
        start() {
          this.started = true;
        },
        stop() {
          this.stopped = true;
          this.onended?.();
        },
      };
      sources.push(source);
      return source;
    }
  }
  globalThis.window = { AudioContext: Audio };
  globalThis.fetch = async () => ({
    ok: true,
    arrayBuffer: async () => new ArrayBuffer(2),
  });
  try {
    const sound = new SparklerSound();
    assert.equal(made, 0);
    await sound.prepare();
    assert.equal(sound.master.gain.value, 2);
    assert.ok(sound.limiter.curve.every((value) => Math.abs(value) < 1));
    assert.equal(sources.length, 0);
    sound.start();
    assert.equal(sound.source.loop, true);
    assert.equal(sound.source.started, true);
    assert.equal(sources.length, 2);
    sound.update(0.1, 0.2);
    const early = sound.envelope.gain.value;
    sound.ctx.currentTime = 4;
    sound.update(0.3, 0.8);
    assert.equal(sound.pops.size, 1);
    sound.update(0.98, 0.8);
    assert.ok(sound.envelope.gain.value < early);
    assert.ok(sound.pan.pan.value > 0);
    sound.setMix(0.3, true);
    assert.equal(sound.master.gain.value, 0);
    sound.setMix(0.3, false);
    assert.equal(sound.master.gain.value, 0.3);
    await sound.ctx.suspend();
    assert.equal(sound.source.stopped, undefined);
    await sound.resume();
    const loop = sound.source;
    sound.stop();
    assert.ok(loop.stopped);
    assert.equal(sound.source, null);
    sound.dispose();
    assert.equal(sound.ctx.state, "closed");
    assert.equal(sound.buffer, null);
  } finally {
    globalThis.window = oldWindow;
    globalThis.fetch = oldFetch;
  }
});
